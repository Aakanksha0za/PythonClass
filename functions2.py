def create_animal(name, color, food, power):

    print("\n----- MAGIC ANIMAL REPORT -----")
    print("Animal Name:", name)
    print("Favorite Color:", color)
    print("Favorite Food:", food)
    print("Special Power:", power)

    print("\nStory Time:")

    print(name, "woke up early today.")
    print(name, "painted itself", color)
    print(name, "ate", food, "for breakfast.")

    print("Suddenly...", name,
          "used", power,
          "and started flying upside down!")

    print(name,
          "then danced with monkeys and sang:")

    print('"Pizza Pizza Hurray! Bananas save the day!"')

    print("\nMission Complete")
    print(name, "became the funniest animal in the world.")
    print("------------------------------")


create_animal(
"Super Bunny",
"Purple",
"100 Ice Creams",
"Laser Eyes"
)

